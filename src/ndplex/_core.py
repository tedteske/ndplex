import itertools as it
import operator
import pickle
import warnings

import numpy as np

__all__ = ["ndplex"]

# Padding and fill values below are created with np.zeros or assigned as the
# Python int 0. For dtype=object both give Python int zeros, so sums of
# object arrays stay exact (the notebook padded with np.pad, which inserts
# numpy int64 zeros: audit finding N12).


def _trim_outside(values, inside):
    """Trim trailing positions that lie wholly outside the array.

    `inside` has the shape of `values` and is True where a value was read
    from the array (False where it is zero padding). Along each axis, the
    result ends at the last position with any value read from the array,
    so genuine zeros are kept and an all-zero line returns zeros.
    """
    slices = []
    for axis in range(values.ndim):
        others = tuple(a for a in range(values.ndim) if a != axis)
        hits = np.flatnonzero(inside.any(axis=others))
        slices.append(slice(hits[-1] + 1 if hits.size else 0))
    return values[tuple(slices)]


class ndplex(np.ndarray):
    """
    n-Dimensional m-Plex (ndplex) array: a generic Pascal's rectangle, cube,
    or higher-dimensional array, as a numpy array subclass.

    By default, a square array of integers with ones on the top and left
    edges and every interior node generated by Pascal's rule (the sum of the
    node above and the node to the left). Any number of edges, any edge
    values and any node-generating function may be given instead.

    Parameters
    ----------
    nrows : int >= 1
        Length of each edge; the array has shape (nrows,) * ndim.
    edges : int, or sequence of numbers or 1-D sequences of length nrows
        The front edges. An int n means n edges of ones. The number of edges
        sets ndim. Edge k lies along axis k (all other coordinates 0): in
        2-D, edges[0] fills column 0 and edges[1] fills row 0. Where edges
        meet, at the origin, the last edge's value is kept.
    arg_locs : None or sequence of sequences of ints <= 0 or None
        Locations, relative to the node being generated, of the arguments
        passed to `func`, in that order. None (the default) means the
        neighbour one step back along each axis: [[-1, 0], [0, -1]] in 2-D.
        A None coordinate means "on the edge" (coordinate 0 on that axis).
        A location outside the array reads 0. Positive offsets are not
        allowed (those nodes have not been computed yet).
    func : callable
        Called with the list of argument values for each interior node;
        returns the node's value. Default: the builtin `sum`.
    dtype : numpy dtype
        Default np.int64 on every platform. int64 is exact only while every
        node fits: the default 2-D array is exact for i + j <= 66 and the
        default 3-D array for i + j + k <= 43. If any node overflows, one
        RuntimeWarning names the first node that did; values are kept as
        numpy computes them (wrapped modulo 2**64). Use dtype=object for
        exact integers of any size, or reduce inside `func` (for example a
        modulus) when only a residue is needed.

    Attributes
    ----------
    nrows : int or None
        Length of each edge, read from the shape (None if the sides differ,
        as for some slices).
    edges, func, arg_locs : the parameters the array was built with,
        carried along by slices, copies and arithmetic as a record; they are
        not used after construction.

    Methods
    -------
    diag(loc, move, sum_axis)
        A line or cross-section through the array.
    as_tri(start, end, sums)
        The array as a triangle (2-D), tetrahedron (3-D) or n-simplex.

    Notes
    -----
    Slices and arithmetic return ndplex arrays; reductions such as `sum`
    and `max` return plain numpy scalars; `diag` and `as_tri` return plain
    numpy arrays. Pickling keeps the attributes, except a `func` that cannot
    itself be pickled (such as a lambda), which comes back as None.
    """

    def __new__(cls, nrows, edges=(1, 1), arg_locs=None, func=sum,
                dtype=np.int64):
        if nrows < 1:
            raise ValueError(f"nrows must be at least 1, got {nrows}")

        if isinstance(edges, (int, np.integer)):
            if edges < 1:
                raise ValueError(f"edges must be at least 1, got {edges}")
            edges = (1,) * int(edges)
        ndim = len(edges)
        if ndim < 1:
            raise ValueError("edges must not be empty")
        for k, e in enumerate(edges):
            shape_e = np.shape(e)
            if not (shape_e == () or shape_e == (nrows,)):
                raise ValueError(
                    f"edge {k} must be a number or a 1-D sequence of length "
                    f"nrows={nrows}; got shape {shape_e}")

        base = np.zeros((nrows,) * ndim, dtype=dtype)

        # Populate the front edges: rotate the axes so that each edge in turn
        # lies along the last axis, and fill it. After ndim rotations the
        # axes are back in their original order.
        view = base
        edge_loc = (0,) * (ndim - 1) + (slice(None),)
        for k in range(ndim):
            view = np.moveaxis(view, 0, -1)
            view[edge_loc] = edges[k]

        if arg_locs is None or len(arg_locs) == 0:
            arg_locs = -np.eye(ndim, dtype=int)
            offsets = [tuple(int(v) for v in row) for row in arg_locs]
        else:
            offsets = []
            for loc in arg_locs:
                if len(loc) != ndim:
                    raise ValueError(
                        f"each arg_loc needs {ndim} coordinates, got "
                        f"{tuple(loc)}")
                offset = []
                for v in loc:
                    if v is not None:
                        v = operator.index(v)
                        if v > 0:
                            raise ValueError(
                                f"arg_locs offsets must be <= 0 (or None), "
                                f"got {tuple(loc)}")
                    offset.append(v)
                offsets.append(tuple(offset))

        zero = base.dtype.type(0)  # for dtype=object, the Python int 0
        first_overflow = None
        with np.errstate(over="raise"):
            for node in it.product(range(nrows), repeat=ndim):
                if node.count(0) >= ndim - 1:
                    continue  # on an edge
                args = []
                for offset in offsets:
                    target = tuple(0 if o is None else n + o
                                   for n, o in zip(node, offset))
                    args.append(zero if min(target) < 0 else base[target])
                try:
                    value = func(args)
                except FloatingPointError:
                    # numpy reports the overflow; keep its wrapped value.
                    with np.errstate(over="ignore"):
                        value = func(args)
                    if first_overflow is None:
                        first_overflow = node
                base[node] = value

        if first_overflow is not None:
            warnings.warn(
                f"ndplex: node values overflowed {base.dtype} from node "
                f"{first_overflow} on (in generation order); that node and "
                f"those computed from it are wrong. Use dtype=object for exact "
                f"integers, or reduce inside func (e.g. a modulus).",
                RuntimeWarning, stacklevel=2)

        obj = base.view(cls)
        obj.edges, obj.func, obj.arg_locs = edges, func, arg_locs
        return obj

    # --- numpy subclass plumbing ---------------------------------------------

    def __array_finalize__(self, obj):
        self.edges = getattr(obj, "edges", None)
        self.func = getattr(obj, "func", None)
        self.arg_locs = getattr(obj, "arg_locs", None)

    def __array_wrap__(self, obj, context=None, return_scalar=False):
        out = super().__array_wrap__(obj, context)
        if out.ndim == 0:
            return out[()]  # reductions give plain scalars
        return out

    def __reduce__(self):
        constructor, args, state = super().__reduce__()
        func = self.func
        try:
            pickle.dumps(func)
        except Exception:
            func = None
        return constructor, args, (state, (self.edges, func, self.arg_locs))

    def __setstate__(self, state):
        array_state, (edges, func, arg_locs) = state
        super().__setstate__(array_state)
        self.edges, self.func, self.arg_locs = edges, func, arg_locs

    @property
    def nrows(self):
        """Length of each edge, from the shape; None if the sides differ."""
        s = self.shape
        if s and all(x == s[0] for x in s):
            return s[0]
        return None

    # --- lines and cross-sections --------------------------------------------

    def _line(self, loc, move):
        """Values along the moves from loc, and where they lie in the array.

        Returns (values, inside): plain arrays of the same shape, one axis
        per move (last move first) plus any axes loc does not fix. Positions
        outside the array hold zero and are False in `inside`.
        """
        a = np.asarray(self)
        if len(loc) == 0:
            loc = (0,) * a.ndim
        k = len(loc)
        if len(move) == 0:
            move = (1,) * k
        if np.isscalar(move[0]):
            move = [move]
        if k > a.ndim:
            raise ValueError(f"loc has {k} coordinates; the array has "
                             f"{a.ndim} dimensions")
        for m in move:
            if len(m) != k:
                raise ValueError(f"each move needs {k} coordinates (as many "
                                 f"as loc), got {tuple(m)}")

        steps = np.arange(max(a.shape))
        coords = []
        for dim in range(k):
            c = loc[dim]
            for i in range(len(move)):
                step_grid = np.broadcast_to(steps, (len(steps),) * (i + 1)).T
                c = step_grid * move[i][dim] + c
            coords.append(c)
        coords = np.stack(coords)

        bounds = np.array(a.shape[:k]).reshape((k,) + (1,) * (coords.ndim - 1))
        inside = ((coords >= 0) & (coords < bounds)).all(axis=0)
        index = tuple(np.where(inside, coords, 0))
        values = a[index]
        rest = (1,) * (values.ndim - inside.ndim)
        inside = np.broadcast_to(inside.reshape(inside.shape + rest),
                                 values.shape)
        values[~inside] = 0
        return values, inside

    def diag(self, loc=(), move=(), sum_axis=None):
        """
        A diagonal: a line or cross-section through the array.

        Starts at the node (or, with fewer coordinates than dimensions, the
        sub-array) `loc` and steps through the array by `move`, returning
        the values it passes. With several moves, the result has one axis
        per move, the last move first.

        Parameters
        ----------
        loc : tuple of ints
            Starting coordinates. Default: the origin.
        move : tuple of ints, or list of such tuples
            Step(s), each with as many coordinates as loc. Default: one step
            along every axis that loc fixes (with the default loc, the main
            diagonal).
        sum_axis : None or int
            If given, sum the result over this axis.

        Returns
        -------
        numpy.ndarray (0-d for a single node), or its sums over sum_axis.

        Notes
        -----
        The result ends where the moves leave the array, so its length is
        set by the geometry, not the values: genuine trailing zeros are
        kept, and a line of zeros returns zeros. Positions outside the array
        but before the end read as 0.
        """
        values, inside = self._line(loc, move)
        values = np.squeeze(values)
        inside = np.squeeze(inside)
        result = _trim_outside(values, inside)
        if sum_axis is None:
            return result
        return result.sum(axis=sum_axis)

    def as_tri(self, start=0, end=None, sums=False):
        """
        The array as a triangle (2-D), tetrahedron (3-D), 4-simplex (4-D),
        and so on: the series of (n-1)-dimensional cross-sections through
        the array along its anti-diagonals.

        In the simplest case, Pascal's rectangle as Pascal's triangle,
        justified left. Returns the result (it does not print it).

        Parameters
        ----------
        start, end : int
            First and last row (2-D) or layer (3-D and up). Default: all.
        sums : bool
            If True, return the sum of each row or layer instead.

        Returns
        -------
        numpy.ndarray
            If sums is False, shape (end - start + 1,) + (end + 1,) * (ndim - 1),
            with each cross-section padded with zeros on the right. If sums is
            True, the 1-D array of sums. A genuine zero in a cross-section is
            indistinguishable from the padding.
        """
        a = np.asarray(self)
        if a.ndim < 2:
            raise ValueError("as_tri needs an array of at least 2 dimensions")
        if any(x != a.shape[0] for x in a.shape):
            raise ValueError(f"as_tri needs equal sides; the shape is {a.shape}")
        ndim = a.ndim
        if end is None:
            end = a.shape[0] - 1

        # The moves follow this pattern (move[0] differs from the rest):
        #   2-D: [(-1, 1)]
        #   3-D: [(0, -1, 1), (1, -1, 0)]
        #   4-D: [(0, 0, -1, 1), (0, 1, -1, 0), (1, -1, 0, 0)]
        ones = np.ones(ndim, dtype=int)
        neg_ones = -np.ones(ndim - 1, dtype=int)
        moves = np.delete(np.flip(np.diag(ones, 0) + np.diag(neg_ones, 1),
                                  axis=0), 0, 0)
        moves[0] = moves[0] * -1  # reverses 1 and -1 in move[0]
        loc = [0] * ndim  # the cross-section starts at loc[-2] = i

        width = (end + 1,) * (ndim - 1)
        rows = []
        for i in range(start, end + 1):
            loc[-2] = i
            values, inside = self._line(tuple(loc), moves)
            section = _trim_outside(values, inside)
            row = np.zeros(width, dtype=a.dtype)
            row[tuple(slice(s) for s in section.shape)] = section
            rows.append(row)

        tri = np.stack(rows, axis=0)
        if sums:
            return tri.sum(axis=tuple(range(1, ndim)))
        return tri
